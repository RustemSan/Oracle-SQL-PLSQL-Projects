-- Cleanup: Drop existing tables to ensure a clean state
BEGIN
    -- Disable constraints to avoid dependency errors during drop
    FOR i IN (SELECT constraint_name, table_name FROM user_constraints WHERE constraint_type = 'R') LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE ' || i.table_name || ' DROP CONSTRAINT ' || i.constraint_name;
    END LOOP;

    -- Drop all tables
    FOR i IN (SELECT table_name FROM user_tables) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || i.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
