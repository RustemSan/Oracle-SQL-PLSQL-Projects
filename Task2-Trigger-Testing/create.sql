-- ------------------------------------------------------------------
-- IO 2: Trigger to prevent overselling tickets (Aircraft Capacity)
-- Implementation based on Lecture Section 9.4
-- ------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_ticket_capacity
FOR INSERT ON ticket
COMPOUND TRIGGER

    TYPE t_count_tab IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    v_ticket_counts t_count_tab;

    -- Step 1: Count current tickets for all flights
    BEFORE STATEMENT IS
    BEGIN
        FOR r IN (SELECT id_flight, COUNT(*) as cnt FROM ticket GROUP BY id_flight) LOOP
            v_ticket_counts(r.id_flight) := r.cnt;
        END LOOP;
    END BEFORE STATEMENT;

    -- Step 2: Check capacity for each new ticket
    BEFORE EACH ROW IS
        v_capacity NUMBER;
        v_current  NUMBER := 0;
    BEGIN
        -- Get plane capacity for this flight
        SELECT p.capacity INTO v_capacity
        FROM flight f
        JOIN plane p ON f.id_plane = p.id_plane
        WHERE f.id_flight = :NEW.id_flight;

        IF v_ticket_counts.EXISTS(:NEW.id_flight) THEN
            v_current := v_ticket_counts(:NEW.id_flight);
        END IF;

        IF v_current >= v_capacity THEN
            RAISE_APPLICATION_ERROR(-20002, 'IO Violation: Flight ' || :NEW.id_flight || ' is full (Capacity: ' || v_capacity || ').');
        END IF;

        -- Update internal counter for the next row in same statement
        v_ticket_counts(:NEW.id_flight) := v_current + 1;
    END BEFORE EACH ROW;
END trg_ticket_capacity;
